#include "libft.h"

char	*ft_strdup(const char *s)
{
	char	*p;
	size_t	len;
	int		i;

	i = 0;
	len = ft_strlen(s);
	p = malloc(len + 1);
	if (!p)
		return (NULL);
	while (s[i])
	{
		p[i] = s[i];
		i++;
	}
	p[i] = '\0';
	return (p);
}
