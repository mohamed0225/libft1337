#include "libft.h"

char	*ft_strjoin(char const *s1, char const *s2)
{
	size_t	sum;
	size_t	i;
	char	*p;

	if (!s1 && !s2)
		return (NULL);
	if (!s1)
		return (ft_strdup(s2));
	else if (!s2)
		return (ft_strdup(s1));
	else
		sum = ft_strlen(s1) + ft_strlen(s2);
	if (ft_strlen(s1) > SIZE_MAX - ft_strlen(s2) - 1)
		return (NULL);
	p = malloc((sum + 1) * sizeof(char));
	if (!p)
		return (NULL);
	i = 0;
	while (*s1)
		p[i++] = *s1++;
	while (*s2)
		p[i++] = *s2++;
	p[i] = '\0';
	return (p);
}
